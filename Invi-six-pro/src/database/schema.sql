-- Competitive state shared by all application instances.

CREATE TABLE IF NOT EXISTS seasons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name TEXT NOT NULL,

    starts_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL,
    ends_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL,

    status TEXT NOT NULL DEFAULT 'scheduled'
        CHECK (
            status IN (
                'scheduled',
                'active',
                'finished'
            )
        ),

    created_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMP(0) WITHOUT TIME ZONE
);
CREATE TABLE IF NOT EXISTS player_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    player_id BIGINT NOT NULL,
    season_id BIGINT NOT NULL,

    points BIGINT NOT NULL DEFAULT 0,

    wins BIGINT NOT NULL DEFAULT 0,
    losses BIGINT NOT NULL DEFAULT 0,
    matches_played BIGINT NOT NULL DEFAULT 0,

    FOREIGN KEY (season_id)
        REFERENCES seasons(id)
        ON DELETE CASCADE,

    UNIQUE (
        player_id,
        season_id
    )
);
CREATE TABLE IF NOT EXISTS matchmaking_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    player_id BIGINT NOT NULL UNIQUE,

    joined_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    match_code TEXT NOT NULL UNIQUE,
    version BIGINT NOT NULL DEFAULT 0,
    is_simulation BIGINT NOT NULL DEFAULT 0 CHECK(is_simulation IN (0,1)),
    ready_deadline TIMESTAMP(0) WITHOUT TIME ZONE,
    draft_bans_required BIGINT NOT NULL DEFAULT 0 CHECK(draft_bans_required IN (0,1)),

    season_id BIGINT NOT NULL,

    status TEXT NOT NULL DEFAULT 'ready_check'
        CHECK (
            status IN (
                'ready_check',
                'captain_vote',
                'draft',
                'veto',
                'side_selection',
                'playing',
                'pending_confirmation',
                'finished',
                'disputed',
                'cancelled'
            )
        ),

    map_name TEXT,

    team_a_side TEXT
        CHECK (
            team_a_side IS NULL
            OR team_a_side IN (
                'attack',
                'defense'
            )
        ),

    team_b_side TEXT
        CHECK (
            team_b_side IS NULL
            OR team_b_side IN (
                'attack',
                'defense'
            )
        ),

    winner_team TEXT
        CHECK (
            winner_team IS NULL
            OR winner_team IN (
                'A',
                'B'
            )
        ),

    result_reported_by BIGINT,

    result_reported_team TEXT
        CHECK (
            result_reported_team IS NULL
            OR result_reported_team IN (
                'A',
                'B'
            )
        ),

    result_confirmed_by BIGINT,

    points_applied BIGINT NOT NULL DEFAULT 0
        CHECK (
            points_applied IN (
                0,
                1
            )
        ),

    created_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    started_at TIMESTAMP(0) WITHOUT TIME ZONE,
    finished_at TIMESTAMP(0) WITHOUT TIME ZONE,

    FOREIGN KEY (season_id)
        REFERENCES seasons(id)
        ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS match_players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    match_id BIGINT NOT NULL,
    player_id BIGINT,
    is_simulated BIGINT NOT NULL DEFAULT 0 CHECK(is_simulated IN (0,1)),
    simulated_nickname TEXT,

    team TEXT
        CHECK (
            team IS NULL
            OR team IN (
                'A',
                'B'
            )
        ),

    is_captain BIGINT NOT NULL DEFAULT 0
        CHECK (
            is_captain IN (
                0,
                1
            )
        ),

    ready BIGINT NOT NULL DEFAULT 0
        CHECK (
            ready IN (
                0,
                1
            )
        ),

    ready_at TIMESTAMP(0) WITHOUT TIME ZONE,

    pick_order BIGINT,

    FOREIGN KEY (match_id)
        REFERENCES matches(id)
        ON DELETE CASCADE,

    UNIQUE (
        match_id,
        player_id
    )
);
CREATE TABLE IF NOT EXISTS captain_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    match_id BIGINT NOT NULL,

    voter_player_id BIGINT,
