-- Reviewed application schema. No legacy users or credentials are imported.
BEGIN;
SET LOCAL search_path TO public, extensions;
CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name TEXT NOT NULL,

    twitch TEXT,

    r6_nickname CITEXT NOT NULL UNIQUE,

    password_hash TEXT NOT NULL,

    role TEXT NOT NULL DEFAULT 'player'
        CHECK (
            role IN (
                'player',
                'staff',
                'admin'
            )
        ),

    status TEXT NOT NULL DEFAULT 'active'
        CHECK (
            status IN (
                'active',
                'inactive',
                'banned'
            )
        ),

    created_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Existing installations: email values and their indexes are intentionally removed.
ALTER TABLE users DROP COLUMN IF EXISTS email;
ALTER TABLE users ADD COLUMN IF NOT EXISTS session_version BIGINT NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS access_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name TEXT NOT NULL,

    claim_token_hash TEXT,
    activated_at TIMESTAMP(0) WITHOUT TIME ZONE,

    r6_nickname CITEXT NOT NULL,

    r6_tracker_url TEXT NOT NULL,

    r6_rank TEXT NOT NULL
        CHECK (
            r6_rank IN (
                'Cobre',
                'Bronze',
                'Prata',
                'Ouro',
                'Platina',
                'Esmeralda',
                'Diamante',
                'Campeão'
            )
        ),

    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (
            status IN (
                'pending',
                'approved',
                'rejected'
            )
        ),

    reviewed_by BIGINT,
    reviewed_at TIMESTAMP(0) WITHOUT TIME ZONE,

    created_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (reviewed_by)
        REFERENCES users(id)
        ON DELETE SET NULL
);
ALTER TABLE access_requests DROP COLUMN IF EXISTS email;
CREATE TABLE IF NOT EXISTS players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL UNIQUE,

    r6_nickname CITEXT NOT NULL UNIQUE,

    r6_tracker_url TEXT,

    r6_rank TEXT NOT NULL
        CHECK (
            r6_rank IN (
                'Cobre',
                'Bronze',
                'Prata',
                'Ouro',
                'Platina',
                'Esmeralda',
                'Diamante',
                'Campeão'
            )
        ),

    created_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE
);
